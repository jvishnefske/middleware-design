//! Telemetry message types for control systems.
//!
//! This module defines the core telemetry message structures that can be
//! serialized to CBOR format for transmission over communication channels.
//!
//! # Traceability
//!
//! - REQ-SER-001: Use CBOR for binary serialization
//! - REQ-SER-002: no_std compatible (minicbor)
//! - REQ-SER-003: All message types derive Encode and Decode
//! - REQ-SER-010: ControlTelemetry message type
//! - REQ-SER-011: PidTelemetry message type
//! - REQ-SER-012: StateMachineTelemetry message type

use minicbor::{Decode, Encode};

/// Telemetry data for control loop execution.
///
/// This message captures the key parameters of a control loop iteration,
/// including timing, setpoint tracking, and output generation.
///
/// # Traceability
///
/// - REQ-SER-010: ControlTelemetry message type
///
/// # Fields
///
/// - `timestamp_ms`: Timestamp in milliseconds since system start
/// - `setpoint`: Desired value for the controlled variable
/// - `measurement`: Actual measured value of the controlled variable
/// - `output`: Control output generated by the controller
/// - `error`: Tracking error (setpoint - measurement)
#[derive(Debug, Clone, Copy, PartialEq, Encode, Decode)]
pub struct ControlTelemetry {
    #[n(0)]
    pub timestamp_ms: u64,
    #[n(1)]
    pub setpoint: f32,
    #[n(2)]
    pub measurement: f32,
    #[n(3)]
    pub output: f32,
    #[n(4)]
    pub error: f32,
}

impl ControlTelemetry {
    /// Creates a new ControlTelemetry instance.
    ///
    /// # Arguments
    ///
    /// - `timestamp_ms`: Timestamp in milliseconds
    /// - `setpoint`: Desired value
    /// - `measurement`: Measured value
    /// - `output`: Controller output
    /// - `error`: Tracking error
    ///
    /// # Returns
    ///
    /// A new ControlTelemetry instance with the specified values.
    pub fn new(
        timestamp_ms: u64,
        setpoint: f32,
        measurement: f32,
        output: f32,
        error: f32,
    ) -> Self {
        Self {
            timestamp_ms,
            setpoint,
            measurement,
            output,
            error,
        }
    }
}

/// Telemetry data for PID controller internal state.
///
/// This message exposes the internal computation of a PID controller,
/// useful for tuning and debugging control performance.
///
/// # Traceability
///
/// - REQ-SER-011: PidTelemetry message type
///
/// # Fields
///
/// - `p_term`: Proportional term contribution
/// - `i_term`: Integral term contribution
/// - `d_term`: Derivative term contribution
/// - `saturated`: True if output is saturated (anti-windup active)
#[derive(Debug, Clone, Copy, PartialEq, Encode, Decode)]
pub struct PidTelemetry {
    #[n(0)]
    pub p_term: f32,
    #[n(1)]
    pub i_term: f32,
    #[n(2)]
    pub d_term: f32,
    #[n(3)]
    pub saturated: bool,
}

impl PidTelemetry {
    /// Creates a new PidTelemetry instance.
    ///
    /// # Arguments
    ///
    /// - `p_term`: Proportional term
    /// - `i_term`: Integral term
    /// - `d_term`: Derivative term
    /// - `saturated`: Saturation flag
    ///
    /// # Returns
    ///
    /// A new PidTelemetry instance with the specified values.
    pub fn new(p_term: f32, i_term: f32, d_term: f32, saturated: bool) -> Self {
        Self {
            p_term,
            i_term,
            d_term,
            saturated,
        }
    }
}

/// Telemetry data for state machine execution.
///
/// This message captures state machine transitions and timing information,
/// useful for monitoring system behavior and debugging state logic.
///
/// # Traceability
///
/// - REQ-SER-012: StateMachineTelemetry message type
///
/// # Fields
///
/// - `state_id`: Current state identifier (as u16)
/// - `state_duration_ms`: Time spent in current state (milliseconds)
/// - `last_transition`: Timestamp of last state transition (milliseconds)
#[derive(Debug, Clone, Copy, PartialEq, Encode, Decode)]
pub struct StateMachineTelemetry {
    #[n(0)]
    pub state_id: u16,
    #[n(1)]
    pub state_duration_ms: u64,
    #[n(2)]
    pub last_transition: u64,
}

impl StateMachineTelemetry {
    /// Creates a new StateMachineTelemetry instance.
    ///
    /// # Arguments
    ///
    /// - `state_id`: Current state identifier
    /// - `state_duration_ms`: Duration in current state
    /// - `last_transition`: Timestamp of last transition
    ///
    /// # Returns
    ///
    /// A new StateMachineTelemetry instance with the specified values.
    pub fn new(state_id: u16, state_duration_ms: u64, last_transition: u64) -> Self {
        Self {
            state_id,
            state_duration_ms,
            last_transition,
        }
    }
}

// test code: a panic is a test failure, which is the intended reporting mechanism
#[cfg_attr(test, allow(clippy::float_cmp))]
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_control_telemetry_new() {
        let telem = ControlTelemetry::new(1000, 10.0, 9.5, 2.5, 0.5);
        assert_eq!(telem.timestamp_ms, 1000);
        assert_eq!(telem.setpoint, 10.0);
        assert_eq!(telem.measurement, 9.5);
        assert_eq!(telem.output, 2.5);
        assert_eq!(telem.error, 0.5);
    }

    #[test]
    fn test_pid_telemetry_new() {
        let telem = PidTelemetry::new(1.0, 0.5, 0.2, false);
        assert_eq!(telem.p_term, 1.0);
        assert_eq!(telem.i_term, 0.5);
        assert_eq!(telem.d_term, 0.2);
        assert!(!telem.saturated);
    }

    #[test]
    fn test_state_machine_telemetry_new() {
        let telem = StateMachineTelemetry::new(3, 5000, 10000);
        assert_eq!(telem.state_id, 3);
        assert_eq!(telem.state_duration_ms, 5000);
        assert_eq!(telem.last_transition, 10000);
    }
}
